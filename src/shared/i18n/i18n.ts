export type StringKey = keyof typeof STRINGS.en;

export function t(
  language: AppLanguage,
  key: StringKey,
  params?: Record<string, string | number | null | undefined>
): string {
  const table = STRINGS[language] ?? STRINGS.en;
  const template = (table as any)[key] ?? STRINGS.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = params ? params[name] : undefined;
    return value == null ? '' : String(value);
  });
}

export function greeting(language: AppLanguage, nickname?: string | null): string {
  const base = language === 'es' ? 'Hola' : language === 'en' ? 'Hi' : 'Hei';
  const trimmed = nickname?.trim();
  return trimmed ? `${base}, ${trimmed}` : base;
}
